import { z } from 'zod';

/**
 * Content schemas for the multi-course hub. Authored JSON and Markdown
 * frontmatter are validated against these at build time
 * (scripts/generate-content.ts); the app reads the generated catalog typed
 * from the same definitions.
 *
 * Ids: every entity has a stable kebab-case local id. Course-scoped entities
 * (modules, lessons, labs, quizzes) get a global id `<courseId>:<localId>`.
 * Ids never derive from display titles or file paths.
 */

// kebab-case: lowercase letters/digits separated by single hyphens.
export const LOCAL_ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const localIdSchema = z.string().regex(LOCAL_ID_PATTERN, 'must be a kebab-case id');

export const LEVELS = ['beginner', 'intermediate', 'advanced'] as const;
export const COURSE_STATUSES = ['active', 'planned'] as const;

export const categorySchema = z.object({
  id: localIdSchema,
  title: z.string().min(1),
  description: z.string().min(1),
});

export const categoriesFileSchema = z.object({
  categories: z.array(categorySchema).min(1),
});

export const moduleManifestSchema = z.object({
  id: localIdSchema,
  title: z.string().min(1),
  description: z.string().min(1),
  /** Lucide icon name. */
  icon: z.string().optional(),
});

export const courseManifestSchema = z.object({
  id: localIdSchema,
  title: z.string().min(1),
  description: z.string().min(1),
  categoryId: localIdSchema,
  level: z.enum(LEVELS),
  /** BCP 47 code of the primary content language. */
  language: z.string().min(2),
  status: z.enum(COURSE_STATUSES),
  icon: z.string().min(1),
  tags: z.array(z.string()).default([]),
  /** Generates this course's content from external sources before indexing. */
  importer: z.enum(['kubernetes-progress', 'ai-engineer-interview']).optional(),
  /** Attribution for courses imported from third-party material; shown on the course overview. */
  source: z
    .object({
      name: z.string().min(1),
      url: z.url(),
      license: z.string().min(1),
      licenseHolder: z.string().min(1),
      /** Learning Hub page that reproduces the license text (local lesson id). */
      licenseLessonId: localIdSchema.optional(),
    })
    .optional(),
  modules: z.array(moduleManifestSchema).min(1),
});

/** Generated by an importer next to course.json: which upstream commit the course was built from. */
export const courseUpstreamSchema = z.object({
  repository: z.string().min(1),
  url: z.url(),
  commit: z.string().regex(/^[0-9a-f]{40}$/),
  commitDate: z.string().min(1),
  importedAt: z.string().min(1),
  contributors: z.array(z.string()),
});

const contentLanguageSchema = z.string().min(2);

export const lessonFrontmatterSchema = z.object({
  type: z.literal('lesson'),
  id: localIdSchema,
  title: z.string().min(1),
  /** Short name for navigation and lists; defaults to the title. */
  navTitle: z.string().min(1).optional(),
  description: z.string().optional(),
  module: localIdSchema,
  order: z.number().int().nonnegative(),
  /** Short label shown on badges, e.g. "Note", "Guide". */
  label: z.string().optional(),
  lang: contentLanguageSchema.optional(),
  relatedLabs: z.array(localIdSchema).default([]),
  /** Original source file for imported content (used by the preservation check). */
  source: z.string().optional(),
});

export const labFrontmatterSchema = z.object({
  type: z.literal('lab'),
  id: localIdSchema,
  title: z.string().min(1),
  description: z.string().optional(),
  module: localIdSchema,
  order: z.number().int().nonnegative(),
  number: z.number().int().positive().optional(),
  lang: contentLanguageSchema.optional(),
  source: z.string().optional(),
});

/** Course-level pages that are neither lessons nor labs, e.g. labs/index.md. */
export const coursePageFrontmatterSchema = z.object({
  type: z.literal('course-page'),
  title: z.string().min(1),
  description: z.string().optional(),
  source: z.string().optional(),
});

export const contentFrontmatterSchema = z.discriminatedUnion('type', [
  lessonFrontmatterSchema,
  labFrontmatterSchema,
  coursePageFrontmatterSchema,
]);

export const quizOptionSchema = z.object({
  id: localIdSchema,
  text: z.string().min(1),
  /** Why this option is right or wrong, shown after answering. */
  explanation: z.string().optional(),
});

export const quizQuestionSchema = z.object({
  id: localIdSchema,
  prompt: z.string().min(1),
  options: z.array(quizOptionSchema).min(2),
  /** One id renders as single choice; several render as "select all that apply". */
  correctOptionIds: z.array(localIdSchema).min(1),
  explanation: z.string().optional(),
});

export const quizFileSchema = z.object({
  id: localIdSchema,
  /** Local id of the lesson this quiz reviews, within the same course. */
  lessonId: localIdSchema,
  title: z.string().min(1),
  questions: z.array(quizQuestionSchema).min(1),
});

export const DIFFICULTIES = ['easy', 'medium', 'hard'] as const;
export const QUESTION_FORMATS = ['multiple-choice', 'open-ended'] as const;

/**
 * A question-bank entry. Text fields ending in `Html` hold sanitized HTML
 * rendered from Markdown at import time (scripts/lib/markdown-html.ts).
 */
export const questionSchema = z.object({
  id: localIdSchema,
  /** Label as shown in the source, e.g. "Q12", "C3", "Prompt A". */
  label: z.string().min(1),
  format: z.enum(QUESTION_FORMATS),
  promptHtml: z.string().min(1),
  difficulty: z.enum(DIFFICULTIES).optional(),
  section: z.string().optional(),
  tags: z.array(z.string()).default([]),
  provenance: z
    .object({
      kind: z.enum(['reported', 'representative']),
      sources: z.array(z.object({ label: z.string(), url: z.string() })),
    })
    .optional(),
  /** Heading anchor of this question on its lesson page. */
  anchor: z.string().min(1),
  options: z
    .array(z.object({ id: localIdSchema, html: z.string().min(1), explanationHtml: z.string().optional(), isCorrect: z.boolean() }))
    .optional(),
  /** Open-ended answer, or the whole explanation block when per-option explanations are unavailable. */
  answerHtml: z.string().optional(),
});

export const questionSetFileSchema = z.object({
  id: localIdSchema,
  topic: z.string().min(1),
  /** Lesson (local id) that shows these questions in context. */
  lessonId: localIdSchema,
  /** Lessons (local ids) whose material this set practices. */
  relatedLessonIds: z.array(localIdSchema).default([]),
  questions: z.array(questionSchema).min(1),
});

export const learningPathItemSchema = z.discriminatedUnion('type', [
  z.object({ type: z.literal('course'), courseId: localIdSchema }),
  z.object({ type: z.literal('module'), courseId: localIdSchema, moduleId: localIdSchema }),
]);

export const learningPathSchema = z.object({
  id: localIdSchema,
  title: z.string().min(1),
  description: z.string().min(1),
  items: z.array(learningPathItemSchema).min(1),
});

export type CategoryManifest = z.infer<typeof categorySchema>;
export type CourseManifest = z.infer<typeof courseManifestSchema>;
export type LessonFrontmatter = z.infer<typeof lessonFrontmatterSchema>;
export type LabFrontmatter = z.infer<typeof labFrontmatterSchema>;
export type ContentFrontmatter = z.infer<typeof contentFrontmatterSchema>;
export type QuizFile = z.infer<typeof quizFileSchema>;
export type QuestionFile = z.infer<typeof questionSchema>;
export type QuestionSetFile = z.infer<typeof questionSetFileSchema>;
export type CourseUpstream = z.infer<typeof courseUpstreamSchema>;
export type Difficulty = (typeof DIFFICULTIES)[number];
export type QuestionFormat = (typeof QUESTION_FORMATS)[number];
export type LearningPathItem = z.infer<typeof learningPathItemSchema>;
export type LearningPathManifest = z.infer<typeof learningPathSchema>;
export type Level = (typeof LEVELS)[number];
export type CourseStatus = (typeof COURSE_STATUSES)[number];

export function toGlobalId(courseId: string, localId: string): string {
  return `${courseId}:${localId}`;
}

export function checklistItemId(labGlobalId: string, anchor: string): string {
  return `${labGlobalId}#${anchor}`;
}
